#!/usr/bin/env bash
# Builds and runs the production stack (deploy/docker-compose.yml).
#
#   deploy/scripts/deploy.sh            build + start (same as `up`); safe to re-run — it is also how you update
#   deploy/scripts/deploy.sh down       stop (data volumes are kept)
#   deploy/scripts/deploy.sh status     containers, health, and what Funnel publishes
#   deploy/scripts/deploy.sh logs [svc] follow logs (api | web | gateway | db)
#   deploy/scripts/deploy.sh reset --demo|--clean --yes
#                                       ERASES the database and uploads (after a backup) and starts over: --demo loads the
#                                       demo centre (staff, ~180 students, groups, lessons…) behind a secret password,
#                                       --clean makes an empty organization with a single owner. Without --yes it refuses.
#
# First run: generates deploy/.env with fresh random secrets (JWT key, database passwords, first admin password) and
# never overwrites it afterwards. In the default (clean) mode the first administrator's temporary password is written
# once to deploy/secrets/first-login.txt — read it, sign in (you are forced to choose your own password), delete the
# file. In demo mode (BOOTSTRAP_MODE=Demo, or `reset --demo`) the demo accounts' shared secret password is written to
# deploy/secrets/demo-accounts.txt instead.
# Publishing to the internet is a separate, deliberate step: deploy/scripts/funnel.sh on
# (In demo mode the API refuses to start with the demo password published in the repository, "Passw0rd!".)
set -euo pipefail

cd "$(dirname "$0")/.."
export MSYS_NO_PATHCONV=1

ENV_FILE=".env"
SECRETS_DIR="secrets"
LOCAL_SETTINGS="../backend/src/EduCenter.Api/appsettings.Local.json"
COMPOSE=(docker compose --env-file "$ENV_FILE" -f docker-compose.yml)

die() { echo "error: $*" >&2; exit 1; }

# Windows only: leave the file readable by the current user alone (best effort — a no-op elsewhere).
lock_down() {
  command -v icacls >/dev/null 2>&1 && command -v cygpath >/dev/null 2>&1 || return 0
  local target; target="$(cygpath -w "$1")"
  if [[ -d "$1" ]]; then icacls "$target" /inheritance:r /grant:r "${USERNAME}:(OI)(CI)F" >/dev/null 2>&1 || true
  else icacls "$target" /inheritance:r /grant:r "${USERNAME}:F" >/dev/null 2>&1 || true; fi
}

rand_hex() { openssl rand -hex "$1"; }
# Same alphabet as the app's own password generator: nothing that reads ambiguously off a screen (0/O, 1/l/I).
rand_readable() { (head -c 16384 /dev/urandom | tr -dc 'abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789' | head -c "$1") || true; }

detect_public_host() {
  tailscale status --json 2>/dev/null \
    | python -c "import sys, json; print(json.load(sys.stdin)['Self']['DNSName'].rstrip('.'))" 2>/dev/null || true
}

# The DeepSeek key stays in the git-ignored appsettings.Local.json used in development; reuse it rather than asking for it again.
read_deepseek_key() {
  [[ -f "$LOCAL_SETTINGS" ]] || return 0
  python - "$LOCAL_SETTINGS" <<'PY' 2>/dev/null || true
import json, sys
try:
    key = json.load(open(sys.argv[1], encoding="utf-8"))["Ai"]["Providers"]["deepseek"].get("ApiKey", "")
    print(key if key and not key.lower().startswith(("your", "sk-xxx")) else "", end="")
except Exception:
    pass
PY
}

init_env() {
  [[ -f "$ENV_FILE" ]] && return 0

  local host="${PUBLIC_HOST:-$(detect_public_host)}"
  [[ -n "$host" ]] || die "could not work out the public name — run with PUBLIC_HOST=your-machine.your-tailnet.ts.net"

  local deepseek_key deepseek_enabled=false
  deepseek_key="$(read_deepseek_key)"
  [[ -n "$deepseek_key" ]] && deepseek_enabled=true

  echo "Generating $ENV_FILE with fresh secrets (public name: $host)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/scripts/deploy.sh on $(date -u +%Y-%m-%dT%H:%MZ). Git-ignored. Back it up somewhere safe: the
# database password in here cannot be recovered from the database volume.
PUBLIC_HOST=$host
GATEWAY_PORT=${GATEWAY_PORT:-8088}

DB_SUPERUSER_PASSWORD=$(rand_hex 24)
APP_DB_NAME=educenter
APP_DB_USER=educenter_app
APP_DB_PASSWORD=$(rand_hex 24)

# Signs every login token. Changing it signs everybody out.
JWT_SIGNING_KEY=$(rand_hex 48)

# What an empty database starts with: Clean (one organization, one owner) or Demo (the demo centre, behind DEMO_PASSWORD).
# Only read while the database has no organization yet; change it with \`deploy.sh reset --demo|--clean --yes\`.
BOOTSTRAP_MODE=${BOOTSTRAP_MODE:-Clean}
DEMO_PASSWORD=$([[ "${BOOTSTRAP_MODE:-Clean}" == "Demo" ]] && rand_readable 20)

# Clean mode only; scrubbed from this file after the first start.
BOOTSTRAP_ORG_NAME=${BOOTSTRAP_ORG_NAME:-EduCenter}
BOOTSTRAP_ORG_SLUG=${BOOTSTRAP_ORG_SLUG:-educenter}
BOOTSTRAP_ADMIN_EMAIL=${BOOTSTRAP_ADMIN_EMAIL:-admin@educenter.local}
BOOTSTRAP_ADMIN_NAME=${BOOTSTRAP_ADMIN_NAME:-Super Admin}
BOOTSTRAP_ADMIN_PASSWORD=$(rand_readable 20)

DEEPSEEK_ENABLED=$deepseek_enabled
DEEPSEEK_API_KEY=$deepseek_key
# Ollama + Whisper running in the development stack on this machine.
AI_LOCAL_ENABLED=true
EOF
  lock_down "$ENV_FILE"
}

env_value() { grep -E "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2- || true; }

# Sets KEY=value in .env, appending the line when an older .env does not have it yet. Values are generated (letters and
# digits), so no escaping is needed.
set_env() {
  if grep -qE "^$1=" "$ENV_FILE"; then sed -i "s/^$1=.*/$1=$2/" "$ENV_FILE"; else printf '%s=%s\n' "$1" "$2" >> "$ENV_FILE"; fi
  lock_down "$ENV_FILE" # sed -i writes a new file, which does not carry the restriction over
}

wait_healthy() { # container, seconds
  local name="$1" deadline=$((SECONDS + $2)) status
  while (( SECONDS < deadline )); do
    status="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$name" 2>/dev/null || echo missing)"
    [[ "$status" == "healthy" ]] && return 0
    [[ "$status" == "exited" || "$status" == "dead" ]] && return 1
    sleep 3
  done
  return 1
}

record_first_login() {
  local password email host reply
  password="$(env_value BOOTSTRAP_ADMIN_PASSWORD)"
  [[ -n "$password" ]] || return 0 # already handled on an earlier run

  email="$(env_value BOOTSTRAP_ADMIN_EMAIL)"; host="$(env_value PUBLIC_HOST)"

  # Ask the running system rather than trust a log line: does the temporary password still open the account? It does
  # exactly until the owner picks their own (the account demands that at first sign-in).
  reply="$(curl -sS --max-time 20 -H "Host: $host" -H 'Content-Type: application/json' \
    -d "{\"email\":\"$email\",\"password\":\"$password\"}" \
    "http://127.0.0.1:$(env_value GATEWAY_PORT)/api/auth/login" 2>/dev/null || true)"

  if grep -q '"mustChangePassword":true' <<<"$reply"; then
    mkdir -p "$SECRETS_DIR"; lock_down "$SECRETS_DIR"
    umask 077
    cat > "$SECRETS_DIR/first-login.txt" <<EOF
EduCenter — first sign-in
Address:   https://${host}/
Email:     ${email}
Password:  ${password}   (temporary — you are asked to choose your own at first sign-in)

Delete this file once you have signed in.
EOF
    lock_down "$SECRETS_DIR/first-login.txt"
    echo
    echo "First administrator ready. Credentials: deploy/$SECRETS_DIR/first-login.txt"
  fi

  # Either way the value has done its job: take it out of .env and out of the running container.
  set_env BOOTSTRAP_ADMIN_PASSWORD ""
  "${COMPOSE[@]}" up -d api >/dev/null
  wait_healthy educenter-prod-api-1 240 || die "api did not come back healthy — see: deploy.sh logs api"
}

record_demo_accounts() {
  local password host
  password="$(env_value DEMO_PASSWORD)"; host="$(env_value PUBLIC_HOST)"
  [[ -n "$password" ]] || return 0

  mkdir -p "$SECRETS_DIR"; lock_down "$SECRETS_DIR"
  umask 077
  cat > "$SECRETS_DIR/demo-accounts.txt" <<EOF
EduCenter — demo accounts
Address:   https://${host}/
Password:  ${password}      (the same for every demo account)

Role             Email
SuperAdmin       superadmin@demo-center.test
Administrator    admin@demo-center.test
Operator         operator@demo-center.test
Teacher          teacher@demo-center.test
Support teacher  support@demo-center.test
Student          student@demo-center.test
Parent           parent@demo-center.test
Developer        developer@demo-center.test
(plus ~14 more teachers, ~180 students and their parents — same password)

Whoever holds this password and an email IS that account. SuperAdmin can change and delete everything, and uses the AI
budget; hand out the Student / Teacher / Parent accounts unless someone needs more. The published "Passw0rd!" does not work here.
EOF
  lock_down "$SECRETS_DIR/demo-accounts.txt"

  # Clean-mode leftovers: a demo deployment has no separate owner account to hand over.
  if [[ -n "$(env_value BOOTSTRAP_ADMIN_PASSWORD)" ]]; then
    set_env BOOTSTRAP_ADMIN_PASSWORD ""
    "${COMPOSE[@]}" up -d api >/dev/null
    wait_healthy educenter-prod-api-1 240 || die "api did not come back healthy — see: deploy.sh logs api"
  fi
  echo
  echo "Demo accounts: deploy/$SECRETS_DIR/demo-accounts.txt"
}

cmd_reset() {
  local mode="" confirmed=0 arg
  for arg in "$@"; do
    case "$arg" in
      --demo) mode=Demo ;;
      --clean) mode=Clean ;;
      --yes) confirmed=1 ;;
      *) die "unknown option '$arg' (reset --demo|--clean --yes)" ;;
    esac
  done
  [[ -n "$mode" ]] || die "reset needs --demo or --clean"
  [[ -f "$ENV_FILE" ]] || die "nothing to reset: there is no $ENV_FILE yet — run deploy.sh first"
  (( confirmed )) || die "reset ERASES the production database and every uploaded file (a backup is taken first). Add --yes to go ahead."

  echo "Backing up before erasing anything…"
  bash scripts/backup.sh || die "the backup failed, so nothing was erased (is the stack running? deploy.sh up)"

  "${COMPOSE[@]}" down
  docker volume rm educenter-prod_pgdata educenter-prod_appdata >/dev/null

  set_env BOOTSTRAP_MODE "$mode"
  if [[ "$mode" == "Demo" ]]; then
    set_env DEMO_PASSWORD "$(rand_readable 20)"
    set_env BOOTSTRAP_ADMIN_PASSWORD ""
  else
    set_env DEMO_PASSWORD ""
    set_env BOOTSTRAP_ADMIN_PASSWORD "$(rand_readable 20)"
  fi
  rm -f "$SECRETS_DIR/first-login.txt" "$SECRETS_DIR/demo-accounts.txt"

  cmd_up
}

cmd_up() {
  command -v docker >/dev/null || die "docker is not installed or not on PATH"
  docker info >/dev/null 2>&1 || die "docker is not running"
  init_env

  echo "Building images (first build takes a few minutes)…"
  "${COMPOSE[@]}" build
  "${COMPOSE[@]}" up -d

  echo "Waiting for the stack to become healthy…"
  wait_healthy educenter-prod-db-1 120 || die "database did not become healthy — see: deploy.sh logs db"
  wait_healthy educenter-prod-api-1 240 || die "api did not become healthy — see: deploy.sh logs api"
  wait_healthy educenter-prod-web-1 120 || die "web did not become healthy — see: deploy.sh logs web"
  wait_healthy educenter-prod-gateway-1 60 || die "gateway did not become healthy — see: deploy.sh logs gateway"

  if [[ "$(env_value BOOTSTRAP_MODE)" == "Demo" ]]; then record_demo_accounts; else record_first_login; fi
  echo
  cmd_status
}

cmd_status() {
  "${COMPOSE[@]}" ps
  echo
  echo "Funnel:"
  tailscale funnel status 2>&1 || true
}

case "${1:-up}" in
  up|update) cmd_up ;;
  down)      "${COMPOSE[@]}" down ;;
  status)    cmd_status ;;
  logs)      shift; "${COMPOSE[@]}" logs -f --tail=100 "$@" ;;
  reset)     shift; cmd_reset "$@" ;;
  *)         die "unknown command '$1' (up | down | status | logs [service] | reset --demo|--clean --yes)" ;;
esac
